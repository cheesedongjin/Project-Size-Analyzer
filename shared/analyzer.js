const TODO_RE = /\b(TODO|FIXME|HACK|XXX|BUG)\b[:\s(]*(.*)/;
const GENERATED_RE = /@generated|auto-?generated|do not edit|generated by/i;
const TEST_RE = /(^|\/)(tests?|__tests__|spec|specs|testing|e2e)\/|(\.|_)(test|spec)s?\.[^/]+$|(^|\/)test_[^/]+\.py$|Tests?\.(cs|java|kt|swift)$/i;
const DOCS_RE = /(^|\/)(docs?|documentation)\//i;
const UNKNOWN = { name: 'Other', color: '#6e7681', type: 'other', line: [], block: [], quotes: [], family: null };

export const CATEGORY_LABELS = {
  source: '소스 코드', test: '테스트', markup: '마크업/스타일', docs: '문서', data: '설정/데이터',
  generated: '생성/잠금 파일', asset: '바이너리/에셋', other: '기타',
};

// 이 문맥 뒤의 '/'는 나눗셈이 아니라 정규식 리터럴의 시작
const REGEX_PREV = /(?:^|[(,=:[!&|?{};+\-*%<>~^]|\breturn|\btypeof|\bcase)\s*$/;
const TOKEN_RE = /[A-Za-z_$][\w$]*|\d[\w.]*|""|\/r\/|===|!==|==|!=|<=|>=|=>|->|&&|\|\||\+\+|--|[+\-*/%]=|::|\?\?|\?\.|<<|>>|[^\s\w"]/g;
const KEYWORDS = new Set(`if else for while do switch case break continue return function var let const new delete typeof instanceof in of class extends implements
import export from try catch finally throw throws async await yield def elif lambda and or not is pass with as raise except global nonlocal
public private protected internal static final void int long short byte float double char bool boolean string struct enum interface package namespace using
fn func fun go defer select match impl trait mut pub use mod where loop when val override abstract virtual sealed readonly get set
this self super null nil None true false True False undefined unless until elsif begin end then foreach goto sizeof template typename operator`.split(/\s+/));
// 중복 탐지에서 제외할 흔한 줄 (괄호만, import 등)
const TRIVIAL_LINE = /^(?:[{}()[\];,]+|(?:import|from|using|#include|package|require|export \* from)\b.*|end|else|\} else \{|return;|break;|continue;|pass|\*\/|\/\*\*?|\*)$/;
const escapeRe = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// ───────────────────────── 파일 단위 분석 ─────────────────────────
export function analyzeText(text, L) {
  if (text.charCodeAt(0) === 0xfeff) text = text.slice(1);
  const lines = text.split(/\r\n|\n|\r/);
  if (lines.length && lines[lines.length - 1] === '') lines.pop();

  const lineTok = L.line || [];
  const blockTok = L.block || [];
  const quotes = L.quotes || [];
  const triggers = [...new Set([...lineTok, ...blockTok.map((b) => b[0]), ...quotes].map((t) => t[0]))];
  const triggerRe = triggers.length ? new RegExp(`[${triggers.map(escapeRe).join('')}]`) : null;
  const fam = L.family ? FAMILIES[L.family] : null;
  const regexLit = L.family === 'js';
  const hasTpl = quotes.includes('`') && L.family === 'js';
  const multi = L.multiline || null;

  let code = 0, comment = 0, blank = 0, decisions = 0, functions = 0;
  let depth = 0, maxDepth = 0, maxLineLen = 0, longLines = 0, lastCode = 0;
  const indents = [0];
  const fstack = [], fnList = [];
  let N1 = 0, N2 = 0;
  const ops = new Set(), opnds = new Set();
  const wantDup = L.type === 'programming' || L.type === 'markup';
  const sigHash = [], sigLine = [], sigLen = [];
  let inBlock = null, inMulti = null;
  const tpl = []; // 템플릿 리터럴 스택: 'T' = 본문, 숫자 = ${} 내부 중괄호 깊이
  const todos = [];

  for (let n = 0; n < lines.length; n++) {
    const line = lines[n];
    const len = line.length;
    if (len > maxLineLen) maxLineLen = len;
    let hasCode = false, hasComment = false, codeText = '', i = 0;

    if (inMulti) {
      // 여러 줄 문자열(파이썬 """…""") 내부
      hasCode = true;
      const end = line.indexOf(inMulti);
      if (end < 0) { code++; continue; }
      i = end + inMulti.length;
      inMulti = null;
      codeText = '""';
    }
    if (tpl.length && tpl[tpl.length - 1] === 'T') hasCode = true; // 템플릿 리터럴 내부에서 시작하는 줄

    if (inBlock) {
      const end = line.indexOf(inBlock);
      if (end < 0) {
        if (line.trim()) { comment++; checkTodo(line, n, todos); } else blank++;
        continue;
      }
      hasComment = true;
      i = end + inBlock.length;
      inBlock = null;
    }

    if (!hasComment && !hasCode && !tpl.length && (!triggerRe || !triggerRe.test(line))) {
      // 빠른 경로: 주석/문자열 시작 문자가 없는 줄
      codeText = line;
      hasCode = line.trim() !== '';
    } else {
      while (i < len) {
        const ch = line[i];
        const top = tpl.length ? tpl[tpl.length - 1] : null;
        if (top === 'T') {
          // 템플릿 리터럴 본문: `…` 종료 또는 ${ 표현식 시작만 확인
          if (ch === '\\') i += 2;
          else if (ch === '`') { tpl.pop(); codeText += '`'; i++; }
          else if (ch === '$' && line[i + 1] === '{') { tpl.push(0); codeText += ' '; i += 2; }
          else i++;
          continue;
        }
        if (ch === ' ' || ch === '\t') { codeText += ch; i++; continue; }
        if (top !== null && (ch === '{' || ch === '}')) {
          // ${ … } 표현식 내부의 중괄호 균형 추적
          if (ch === '}' && top === 0) { tpl.pop(); i++; continue; }
          tpl[tpl.length - 1] += ch === '{' ? 1 : -1;
        }
        let matched = false;
        for (const [s, e] of blockTok) {
          if (line.startsWith(s, i)) {
            hasComment = true; matched = true;
            const end = line.indexOf(e, i + s.length);
            if (end < 0) { inBlock = e; i = len; } else i = end + e.length;
            break;
          }
        }
        if (matched) continue;
        for (const t of lineTok) {
          if (line.startsWith(t, i)) { hasComment = true; matched = true; break; }
        }
        if (matched) break;
        if (ch === '/' && regexLit && REGEX_PREV.test(codeText)) {
          // 정규식 리터럴(/.../)은 내용 대신 자리표시자로 대체
          let j = i + 1, cls = false;
          while (j < len) {
            const cj = line[j];
            if (cj === '\\') j++;
            else if (cj === '[') cls = true;
            else if (cj === ']') cls = false;
            else if (cj === '/' && !cls) break;
            j++;
          }
          if (j < len) { hasCode = true; codeText += '/r/'; i = j + 1; continue; }
        }
        if (ch === '`' && hasTpl) { hasCode = true; tpl.push('T'); codeText += '`'; i++; continue; }
        if (multi) {
          const tok = multi.find((t) => line.startsWith(t, i));
          if (tok) {
            hasCode = true;
            const end = line.indexOf(tok, i + tok.length);
            codeText += '""';
            if (end < 0) { inMulti = tok; i = len; } else i = end + tok.length;
            continue;
          }
        }
        if (quotes.includes(ch)) {
          hasCode = true;
          let j = i + 1;
          while (j < len && line[j] !== ch) { if (line[j] === '\\') j++; j++; }
          codeText += '""';
          i = j + 1;
          continue;
        }
        hasCode = true;
        codeText += ch;
        i++;
      }
    }

    if (hasCode) {
      code++;
      const ln = n + 1;
      if (len > 120) longLines++;
      if (wantDup) {
        // 복사-붙여넣기 탐지용: 공백을 정규화한 의미 있는 줄의 해시
        const norm = line.trim().replace(/\s+/g, ' ');
        if (norm.length >= 4 && !TRIVIAL_LINE.test(norm)) { sigHash.push(fnv32(norm)); sigLine.push(ln); sigLen.push(norm.length); }
      }
      if (fam && codeText.length <= 1000) {
        const brace = fam.nest === 'brace';
        let w = 0;
        if (!brace) {
          // 들여쓰기 스택으로 중첩 단계 계산 (들여쓰기 폭이 달라도 단계 수로 측정)
          for (let k = 0; k < len; k++) { const c = line[k]; if (c === ' ') w++; else if (c === '\t') w += 4; else break; }
          while (indents.length > 1 && indents[indents.length - 1] > w) indents.pop();
          if (w > indents[indents.length - 1]) indents.push(w);
          if (indents.length - 1 > maxDepth) maxDepth = indents.length - 1;
          // 들여쓰기가 함수 시작 줄 이하로 돌아오면 함수 종료
          while (fstack.length && w <= fstack[fstack.length - 1].indent) closeFn(fstack.pop(), lastCode);
        }
        fam.fn.lastIndex = 0;
        const f = codeText.match(fam.fn);
        if (f) {
          functions += f.length;
          fstack.push(openFn(codeText, ln, depth, w));
        }
        fam.decision.lastIndex = 0;
        const d = codeText.match(fam.decision);
        if (d) {
          decisions += d.length;
          if (fstack.length) fstack[fstack.length - 1].dec += d.length;
        }
        if (brace) {
          for (let k = 0; k < codeText.length; k++) {
            const c = codeText.charCodeAt(k);
            if (c === 123) {
              if (++depth > maxDepth) maxDepth = depth;
              const t = fstack[fstack.length - 1];
              if (t && !t.opened && depth > t.depth) t.opened = true;
            } else if (c === 125) {
              if (depth > 0) depth--;
              while (fstack.length && fstack[fstack.length - 1].opened && depth <= fstack[fstack.length - 1].depth) closeFn(fstack.pop(), ln);
            }
          }
          // 본문 중괄호가 없는 함수: 한 줄짜리(화살표 함수 등)로 보거나, 다음 줄의 { 를 기다림(Allman 스타일)
          const t = fstack[fstack.length - 1];
          if (t && !t.opened) {
            if (t.line === ln) { if (!/[(,)]\s*$/.test(codeText)) closeFn(fstack.pop(), ln); }
            else if (ln - t.line > 3) fstack.pop();
          }
        }
        // Halstead: 연산자/피연산자 집계
        TOKEN_RE.lastIndex = 0;
        let m;
        while ((m = TOKEN_RE.exec(codeText))) {
          const tk = m[0], c0 = tk.charCodeAt(0);
          const isWord = (c0 >= 65 && c0 <= 90) || (c0 >= 97 && c0 <= 122) || c0 === 95 || c0 === 36;
          if (isWord) {
            if (KEYWORDS.has(tk)) { N1++; ops.add(tk); } else { N2++; opnds.add(tk); }
          } else if ((c0 >= 48 && c0 <= 57) || tk === '""' || tk === '/r/') { N2++; opnds.add(tk); }
          else { N1++; ops.add(tk); }
        }
      }
      lastCode = ln;
    } else if (hasComment) comment++;
    else blank++;

    if (hasComment) checkTodo(line, n, todos);
  }
  // 파일 끝까지 열린 함수 정리
  while (fstack.length) {
    const t = fstack.pop();
    if (t.opened || t.indent >= 0) closeFn(t, t.opened ? lines.length : lastCode);
  }

  const nesting = fam ? maxDepth : 0;
  const complexity = fam ? decisions + (code > 0 ? 1 : 0) : 0;
  let halstead = null;
  if (fam && N1 + N2 > 0) {
    const n1 = ops.size, n2 = opnds.size || 1;
    const volume = (N1 + N2) * Math.log2(Math.max(2, n1 + n2));
    const difficulty = (n1 / 2) * (N2 / n2);
    halstead = { N1, N2, n1, n2, volume, difficulty, effort: volume * difficulty };
  }
  return {
    lines: lines.length, code, comment, blank,
    complexity, functions, nesting, maxLineLen, longLines, todos,
    fnList, halstead,
    // 원래 정의(Oman & Hagemeister)처럼 함수(모듈) 단위 평균값으로 계산 — 큰 파일이 과도하게 불리해지지 않도록
    mi: halstead && code > 0 ? maintainability(halstead.volume / Math.max(1, fnList.length), complexity / Math.max(1, fnList.length), code / Math.max(1, fnList.length)) : null,
    sig: wantDup ? { h: sigHash, line: sigLine, len: sigLen } : null,
    head: lines.slice(0, 5).join('\n'),
  };

  function openFn(text, ln, d, w) {
    const name = fnName(text);
    return { name, line: ln, depth: d, indent: fam.nest === 'brace' ? -1 : w, opened: false, dec: 0, params: countParams(text, name) };
  }
  function closeFn(t, end) {
    if (fnList.length < 5000) fnList.push({ name: t.name, line: t.line, length: Math.max(1, end - t.line + 1), cx: t.dec + 1, params: t.params });
  }
}

// Visual Studio 방식 유지보수성 지수(0~100)
function maintainability(volume, cc, loc) {
  const mi = 171 - 5.2 * Math.log(Math.max(1, volume)) - 0.23 * cc - 16.2 * Math.log(Math.max(1, loc));
  return Math.max(0, Math.min(100, (mi * 100) / 171));
}

const NOT_NAME = new Set(['if', 'for', 'while', 'switch', 'catch', 'return', 'function', 'new', 'typeof', 'sizeof', 'await', 'async', 'elif', 'foreach', 'using', 'lock', 'with', 'super', 'this', 'fn', 'func', 'fun', 'def']);
function fnName(text) {
  let m = /\bfunction\s*\*?\s*([A-Za-z_$][\w$]*)/.exec(text);
  if (m) return m[1];
  m = /([A-Za-z_$][\w$]*)\s*[:=]\s*(?:async\s*)?(?:function\b|\([^()]*\)\s*(?::[^=]+)?=>|[A-Za-z_$][\w$]*\s*=>)/.exec(text);
  if (m) return m[1];
  m = /\b(?:def|fn|fun|func|sub)\s+(?:\([^)]*\)\s*)?([A-Za-z_][\w]*)/.exec(text);
  if (m) return m[1];
  if (/=>/.test(text) || /\blambda\b/.test(text)) return '(익명)';
  for (const x of text.matchAll(/([A-Za-z_$~][\w$~]*)\s*\(/g)) if (!NOT_NAME.has(x[1])) return x[1];
  return '(익명)';
}

function countParams(text, name) {
  let idx = name && name !== '(익명)' ? text.indexOf(name) : 0;
  if (idx < 0) idx = 0;
  const m = /\(([^()]*)\)/.exec(text.slice(idx));
  if (!m) return /[\w$]\s*=>/.test(text) ? 1 : 0;
  return m[1].split(',').map((s) => s.trim()).filter((s) => s && s !== 'self' && s !== 'this' && s !== 'cls' && s !== 'void').length;
}

function fnv32(str) {
  let h = 0x811c9dc5;
  for (let i = 0; i < str.length; i++) h = Math.imul(h ^ str.charCodeAt(i), 16777619);
  return h >>> 0;
}

function checkTodo(line, n, todos) {
  if (todos.length >= 50) return;
  const m = TODO_RE.exec(line);
  if (m) todos.push({ line: n + 1, tag: m[1], text: m[2].replace(/\*\/\s*$|-->\s*$/, '').trim().slice(0, 160) });
}

// 짧고 빠른 53비트 해시(cyrb53) — 중복 파일 탐지용
function hash53(str) {
  let h1 = 0xdeadbeef, h2 = 0x41c6ce57;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507) ^ Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507) ^ Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return (4294967296 * (2097151 & h2) + (h1 >>> 0)).toString(36);
}

function categorize(path, L, flags) {
  if (flags.binary) return 'asset';
  if (flags.generated || flags.minified) return 'generated';
  if (TEST_RE.test(path) && (L.type === 'programming' || L.type === 'markup')) return 'test';
  if (L.type === 'programming') return 'source';
  if (L.type === 'markup') return 'markup';
  if (L.type === 'prose' || DOCS_RE.test(path)) return 'docs';
  if (L.type === 'data') return 'data';
  return 'other';
}

// ───────────────────────── 의존성 매니페스트 ─────────────────────────
function parseDependencies(path, content) {
  const name = path.split('/').pop().toLowerCase();
  const deps = [];
  const add = (n, v, dev = false) => { if (n) deps.push({ name: n.trim(), version: (v || '').toString().trim(), dev }); };
  try {
    if (name === 'package.json' || name === 'composer.json' || (name === 'manifest.json' && /(^|\/)packages\/manifest\.json$/i.test(path))) {
      const j = JSON.parse(content);
      const prod = name === 'composer.json' ? j.require : j.dependencies;
      const dev = name === 'composer.json' ? j['require-dev'] : j.devDependencies;
      for (const [k, v] of Object.entries(prod || {})) add(k, v);
      for (const [k, v] of Object.entries(dev || {})) add(k, v, true);
      for (const [k, v] of Object.entries(j.peerDependencies || {})) add(k, v);
      if (!deps.length && name === 'manifest.json') return null;
      const eco = name === 'composer.json' ? 'Composer (PHP)' : name === 'manifest.json' ? 'Unity Package Manager' : 'npm';
      return { ecosystem: eco, deps };
    }
    if (/^requirements.*\.txt$/.test(name)) {
      for (const raw of content.split(/\r?\n/)) {
        const l = raw.replace(/#.*/, '').trim();
        if (!l || l.startsWith('-')) continue;
        const m = /^([A-Za-z0-9_.\-[\]]+)\s*(.*)$/.exec(l);
        if (m) add(m[1].replace(/\[.*\]/, ''), m[2], /dev|test/.test(name));
      }
      return { ecosystem: 'pip', deps };
    }
    if (name === 'pyproject.toml') {
      const arr = /^\s*dependencies\s*=\s*\[([\s\S]*?)\]/m.exec(content);
      if (arr) for (const m of arr[1].matchAll(/["']([A-Za-z0-9_.\-]+)([^"']*)["']/g)) add(m[1], m[2]);
      const poetry = /\[tool\.poetry\.dependencies\]([\s\S]*?)(\n\[|$)/.exec(content);
      if (poetry) for (const m of poetry[1].matchAll(/^\s*([A-Za-z0-9_.\-]+)\s*=\s*(.+)$/gm)) if (m[1] !== 'python') add(m[1], m[2].replace(/["'{}]/g, ''));
      return deps.length ? { ecosystem: 'Python', deps } : null;
    }
    if (name === 'go.mod') {
      const block = /require\s*\(([\s\S]*?)\)/.exec(content);
      const lines = block ? block[1].split(/\r?\n/) : [];
      for (const m of content.matchAll(/^require\s+([^\s(]+)\s+(\S+)/gm)) add(m[1], m[2]);
      for (const l of lines) { const m = /^\s*(\S+)\s+(\S+)(\s*\/\/\s*indirect)?/.exec(l); if (m) add(m[1], m[2], !!m[3]); }
      return { ecosystem: 'Go modules', deps };
    }
    if (name === 'cargo.toml') {
      for (const sec of content.matchAll(/\[((?:dev-|build-)?dependencies)\]([\s\S]*?)(?=\n\[|$)/g)) {
        for (const m of sec[2].matchAll(/^\s*([A-Za-z0-9_\-]+)\s*=\s*(.+)$/gm)) {
          const v = /version\s*=\s*"([^"]+)"/.exec(m[2]);
          add(m[1], v ? v[1] : m[2].replace(/"/g, ''), sec[1] !== 'dependencies');
        }
      }
      return { ecosystem: 'Cargo (Rust)', deps };
    }
    if (name === 'gemfile') {
      for (const m of content.matchAll(/^\s*gem\s+["']([^"']+)["'](?:\s*,\s*["']([^"']+)["'])?/gm)) add(m[1], m[2]);
      return { ecosystem: 'Bundler (Ruby)', deps };
    }
    if (/\.(csproj|fsproj|vbproj)$/.test(name) || name === 'directory.packages.props') {
      for (const m of content.matchAll(/<Package(?:Reference|Version)\s+Include="([^"]+)"(?:\s+Version="([^"]*)")?/g)) add(m[1], m[2]);
      return deps.length ? { ecosystem: 'NuGet (.NET)', deps } : null;
    }
    if (name === 'packages.config') {
      for (const m of content.matchAll(/<package\s+id="([^"]+)"\s+version="([^"]*)"/g)) add(m[1], m[2]);
      return { ecosystem: 'NuGet (.NET)', deps };
    }
    if (name === 'pom.xml') {
      for (const m of content.matchAll(/<dependency>([\s\S]*?)<\/dependency>/g)) {
        const g = /<groupId>([^<]+)/.exec(m[1]), a = /<artifactId>([^<]+)/.exec(m[1]), v = /<version>([^<]+)/.exec(m[1]), s = /<scope>([^<]+)/.exec(m[1]);
        add(`${g ? g[1] + ':' : ''}${a ? a[1] : '?'}`, v && v[1], s && s[1] === 'test');
      }
      return { ecosystem: 'Maven (Java)', deps };
    }
    if (name === 'build.gradle' || name === 'build.gradle.kts') {
      for (const m of content.matchAll(/^\s*(implementation|api|compileOnly|runtimeOnly|testImplementation|androidTestImplementation|kapt|ksp|annotationProcessor)\s*\(?\s*["']([^"']+)["']/gm)) {
        const parts = m[2].split(':');
        add(parts.slice(0, 2).join(':'), parts[2], /test/i.test(m[1]));
      }
      return deps.length ? { ecosystem: 'Gradle', deps } : null;
    }
    if (name === 'pubspec.yaml') {
      for (const sec of content.matchAll(/^(dependencies|dev_dependencies):\s*\n((?:[ \t]+.*\n?)*)/gm)) {
        for (const m of sec[2].matchAll(/^ {2}([A-Za-z0-9_]+):\s*(.*)$/gm)) add(m[1], m[2], sec[1] !== 'dependencies');
      }
      return { ecosystem: 'pub (Dart)', deps };
    }
  } catch { /* 깨진 매니페스트는 무시 */ }
  return null;
}

// ───────────────────────── 전체 분석 ─────────────────────────
export function analyze(inputFiles, opts = {}) {
  const onProgress = opts.onProgress || (() => {});
  const files = [];
  const langMap = new Map();
  const extMap = new Map();
  const cats = {};
  const hashMap = new Map();
  const todoItems = [];
  const todoCounts = {};
  const dependencies = [];
  const allFns = [];
  const dupInputs = [];
  const hal = { volume: 0, effort: 0, diffSum: 0, diffW: 0 };
  let maxDepth = 0;

  for (let idx = 0; idx < inputFiles.length; idx++) {
    const f = inputFiles[idx];
    if (idx % 500 === 0) onProgress(idx, inputFiles.length);
    const path = f.path.replace(/\\/g, '/');
    const name = path.split('/').pop();
    const ext = extOf(name);
    const depth = path.split('/').length - 1;
    if (depth > maxDepth) maxDepth = depth;

    const L = detectLanguage(name) || UNKNOWN;
    const isBinary = f.binary || f.content == null;
    const rec = { path, lang: isBinary ? null : L.name, size: f.size || 0, lines: 0, code: 0, comment: 0, blank: 0, cx: 0, fn: 0, nest: 0 };

    if (isBinary) {
      rec.bin = true;
      if (f.skipped) rec.skipped = f.skipped;
    } else {
      const r = analyzeText(f.content, L);
      Object.assign(rec, { lines: r.lines, code: r.code, comment: r.comment, blank: r.blank, cx: r.complexity, fn: r.functions, nest: r.nesting });
      if (L.generated || GENERATED_RE.test(r.head)) rec.gen = true;
      if (/\.min\.(js|css)$/i.test(name) || (['JavaScript', 'CSS'].includes(L.name) && r.lines > 0 && f.content.length / r.lines > 400)) rec.min = true;
      if (r.longLines) rec.ll = r.longLines;
      if (!rec.gen && !rec.min) {
        if (r.mi != null) { rec.mi = Math.round(r.mi * 10) / 10; rec.hv = Math.round(r.halstead.volume); }
        if (r.halstead) { hal.volume += r.halstead.volume; hal.effort += r.halstead.effort; hal.diffSum += r.halstead.difficulty * r.code; hal.diffW += r.code; }
        for (const fn of r.fnList) allFns.push({ path, ...fn });
        if (r.sig && r.sig.h.length >= DUP_K) dupInputs.push({ idx: files.length, ...r.sig });
      }
      for (const t of r.todos) {
        todoCounts[t.tag] = (todoCounts[t.tag] || 0) + 1;
        if (todoItems.length < 500) todoItems.push({ path, ...t });
      }
      if (f.content.length > 0) {
        const h = `${f.content.length}:${hash53(f.content)}`;
        const arr = hashMap.get(h);
        if (arr) arr.push(path); else hashMap.set(h, [path]);
      }
      if (f.content.length < 2_000_000) {
        const d = parseDependencies(path, f.content);
        if (d && d.deps.length) dependencies.push({ file: path, ...d });
      }
    }
    rec.cat = categorize(path, L, { binary: isBinary, generated: rec.gen, minified: rec.min });
    files.push(rec);

    // 언어 집계 (바이너리 제외)
    if (!isBinary) {
      let lg = langMap.get(L.name);
      if (!lg) langMap.set(L.name, (lg = { name: L.name, color: L.color, type: L.type, files: 0, code: 0, comment: 0, blank: 0, lines: 0, bytes: 0, cx: 0, fn: 0 }));
      lg.files++; lg.code += rec.code; lg.comment += rec.comment; lg.blank += rec.blank; lg.lines += rec.lines; lg.bytes += rec.size; lg.cx += rec.cx; lg.fn += rec.fn;
    }
    const ek = ext ? `.${ext}` : '(없음)';
    let ex = extMap.get(ek);
    if (!ex) extMap.set(ek, (ex = { ext: ek, files: 0, bytes: 0, lines: 0 }));
    ex.files++; ex.bytes += rec.size; ex.lines += rec.lines;

    const cg = cats[rec.cat] || (cats[rec.cat] = { files: 0, code: 0, lines: 0, bytes: 0 });
    cg.files++; cg.code += rec.code; cg.lines += rec.lines; cg.bytes += rec.size;
  }
  onProgress(inputFiles.length, inputFiles.length);

  // ── 요약
  const sum = (k) => files.reduce((a, f) => a + f[k], 0);
  const text = files.filter((f) => !f.bin);
  const languages = [...langMap.values()].sort((a, b) => b.code - a.code || b.bytes - a.bytes);
  const codeLangs = languages.filter((l) => (l.type === 'programming' || l.type === 'markup') && l.code > 0);
  const tree = buildTree(files);

  const summary = {
    files: files.length,
    textFiles: text.length,
    binaryFiles: files.length - text.length,
    dirs: tree.dirCount,
    bytes: sum('size'),
    lines: sum('lines'),
    code: sum('code'),
    comment: sum('comment'),
    blank: sum('blank'),
    languages: codeLangs.length,
    allLanguages: languages.filter((l) => l.name !== 'Other').length,
    maxDepth,
    generatedFiles: files.filter((f) => f.gen || f.min).length,
  };
  summary.avgLinesPerFile = text.length ? Math.round(summary.lines / text.length) : 0;
  const srcCode = (cats.source?.code || 0);
  const srcComment = files.filter((f) => f.cat === 'source').reduce((a, f) => a + f.comment, 0);
  summary.commentRatio = srcCode + srcComment ? srcComment / (srcCode + srcComment) : 0;
  summary.testRatio = srcCode + (cats.test?.code || 0) ? (cats.test?.code || 0) / (srcCode + (cats.test?.code || 0)) : 0;

  // ── 복잡도 (생성/최소화 파일 제외, 분기 규칙이 있는 언어만)
  const cxFiles = text.filter((f) => !f.gen && !f.min && f.code > 0 && LANGUAGES[f.lang]?.family);
  const cxTotal = cxFiles.reduce((a, f) => a + f.cx, 0);
  const cxCode = cxFiles.reduce((a, f) => a + f.code, 0);
  const fnTotal = cxFiles.reduce((a, f) => a + f.fn, 0);
  const nestWeighted = cxCode ? cxFiles.reduce((a, f) => a + f.nest * f.code, 0) / cxCode : 0;
  const buckets = [[1, 10, '1–10'], [11, 20, '11–20'], [21, 50, '21–50'], [51, 100, '51–100'], [101, 250, '101–250'], [251, Infinity, '250+']];
  const histogram = buckets.map(([lo, hi, label]) => ({ label, count: cxFiles.filter((f) => f.cx >= lo && f.cx <= hi).length }));
  const complexity = {
    analyzedFiles: cxFiles.length,
    total: cxTotal,
    functions: fnTotal,
    density: cxCode ? (cxTotal / cxCode) * 100 : 0,
    avgPerFile: cxFiles.length ? cxTotal / cxFiles.length : 0,
    // 함수당 순환 복잡도 ≈ 1 + 분기 수 / 함수 수
    avgPerFunction: fnTotal ? (cxTotal - cxFiles.length + fnTotal) / fnTotal : 0,
    avgNesting: nestWeighted,
    maxNesting: cxFiles.reduce((a, f) => Math.max(a, f.nest), 0),
    histogram,
    top: [...cxFiles].sort((a, b) => b.cx - a.cx).slice(0, 25).map(pick),
    deepest: [...cxFiles].sort((a, b) => b.nest - a.nest).slice(0, 10).map(pick),
    byLanguage: languages.filter((l) => l.cx > 0).map((l) => ({ name: l.name, color: l.color, cx: l.cx, code: l.code, density: l.code ? (l.cx / l.code) * 100 : 0, fn: l.fn })),
  };

  // ── 중복 파일
  const dupGroups = [...hashMap.values()].filter((p) => p.length > 1).map((paths) => {
    const size = files.find((f) => f.path === paths[0])?.size || 0;
    return { size, paths, wasted: size * (paths.length - 1) };
  }).sort((a, b) => b.wasted - a.wasted);

  const nonGen = text.filter((f) => !f.gen && !f.min);
  const report = {
    version: 1,
    summary,
    languages,
    extensions: [...extMap.values()].sort((a, b) => b.bytes - a.bytes),
    categories: cats,
    files,
    tree: tree.root,
    complexity,
    score: computeScore(summary, complexity, codeLangs.length, files),
    cocomo: cocomo(srcCode + (cats.test?.code || 0) + (cats.markup?.code || 0)),
    todos: { total: Object.values(todoCounts).reduce((a, b) => a + b, 0), counts: todoCounts, items: todoItems },
    duplicates: { groups: dupGroups.slice(0, 100), groupCount: dupGroups.length, files: dupGroups.reduce((a, g) => a + g.paths.length, 0), wastedBytes: dupGroups.reduce((a, g) => a + g.wasted, 0) },
    largest: [...nonGen].sort((a, b) => b.lines - a.lines).slice(0, 20).map(pick),
    heaviest: [...files].sort((a, b) => b.size - a.size).slice(0, 20).map(pick),
    longFiles: nonGen.filter((f) => f.code > 1000 && f.cat === 'source').length,
    generated: files.filter((f) => f.gen || f.min).slice(0, 100).map(pick),
    dependencies,
    warnings: [],
  };
  onProgress(inputFiles.length, inputFiles.length, '함수 · 유지보수성 · 중복 코드 분석 중…');
  // 함수 통계는 소스 코드만 대상 (테스트의 describe/it 콜백 등은 별도 집계)
  const catOf = new Map(files.map((f) => [f.path, f.cat]));
  report.functions = functionReport(allFns.filter((f) => catOf.get(f.path) === 'source'));
  report.functions.testFunctions = allFns.filter((f) => catOf.get(f.path) === 'test').length;
  report.codeDup = detectDuplication(dupInputs, files);
  report.maintainability = maintainabilityReport(cxFiles, hal);
  report.structure = structureReport(files, tree.root, summary);
  report.modules = modulesReport(files);
  report.summary.longLines = files.reduce((a, f) => a + (f.ll || 0), 0);
  Object.assign(report, detectStack(report));
  report.scope = assessScope(files);
  if (report.scope.files) report.warnings.push(`검증 복사본·실행 데이터가 있을 수 있는 폴더에 ${report.scope.files.toLocaleString()}개 파일이 포함되었습니다 (${(report.scope.ratio * 100).toFixed(1)}%). 제외 규칙을 검토하세요: ${report.scope.candidates.slice(0, 10).map((g) => g.path).join(', ')}. 중복률과 품질 점수가 왜곡될 수 있습니다.`);
  return report;
}

// ───────────────────────── 함수 단위 통계 ─────────────────────────
const bucketize = (values, defs) => defs.map(([lo, hi, label, extra]) => ({ label, count: values.filter((v) => v >= lo && v <= hi).length, ...(extra ? { level: extra } : {}) }));
const median = (arr) => {
  if (!arr.length) return 0;
  const s = [...arr].sort((a, b) => a - b);
  const m = s.length >> 1;
  return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const percentile = (sorted, p) => (sorted.length ? sorted[Math.min(sorted.length - 1, Math.floor(sorted.length * p))] : 0);

function functionReport(fns) {
  const n = fns.length;
  const cxs = fns.map((f) => f.cx), lens = fns.map((f) => f.length), params = fns.map((f) => f.params);
  const sortedLen = [...lens].sort((a, b) => a - b);
  const sortedCx = [...cxs].sort((a, b) => a - b);
  const slim = (f) => ({ path: f.path, name: f.name, line: f.line, length: f.length, cx: f.cx, params: f.params });
  return {
    count: n,
    avgLength: n ? lens.reduce((a, b) => a + b, 0) / n : 0,
    medianLength: median(lens),
    p90Length: percentile(sortedLen, 0.9),
    avgCx: n ? cxs.reduce((a, b) => a + b, 0) / n : 0,
    medianCx: median(cxs),
    p90Cx: percentile(sortedCx, 0.9),
    maxCx: n ? sortedCx[n - 1] : 0,
    avgParams: n ? params.reduce((a, b) => a + b, 0) / n : 0,
    over10: cxs.filter((c) => c > 10).length,
    over20: cxs.filter((c) => c > 20).length,
    over50: cxs.filter((c) => c > 50).length,
    long50: lens.filter((l) => l > 50).length,
    long100: lens.filter((l) => l > 100).length,
    manyParams: params.filter((p) => p > 5).length,
    risk: bucketize(cxs, [[1, 5, '1–5 낮음', 'low'], [6, 10, '6–10 보통', 'moderate'], [11, 20, '11–20 높음', 'high'], [21, 50, '21–50 매우 높음', 'very-high'], [51, Infinity, '50+ 테스트 불가', 'untestable']]),
    lengthBuckets: bucketize(lens, [[1, 10, '1–10'], [11, 25, '11–25'], [26, 50, '26–50'], [51, 100, '51–100'], [101, 200, '101–200'], [201, Infinity, '200+']]),
    paramBuckets: bucketize(params, [[0, 0, '0개'], [1, 1, '1개'], [2, 2, '2개'], [3, 3, '3개'], [4, 4, '4개'], [5, 5, '5개'], [6, Infinity, '6개+']]),
    topComplex: [...fns].sort((a, b) => b.cx - a.cx || b.length - a.length).slice(0, 40).map(slim),
    topLong: [...fns].sort((a, b) => b.length - a.length).slice(0, 40).map(slim),
    topParams: [...fns].filter((f) => f.params > 0).sort((a, b) => b.params - a.params || b.cx - a.cx).slice(0, 20).map(slim),
  };
}

// ───────────────────────── 유지보수성 (Halstead / MI) ─────────────────────────
function maintainabilityReport(cxFiles, hal) {
  const withMi = cxFiles.filter((f) => f.mi != null);
  const code = withMi.reduce((a, f) => a + f.code, 0);
  const avg = code ? withMi.reduce((a, f) => a + f.mi * f.code, 0) / code : 0;
  const mis = withMi.map((f) => f.mi);
  return {
    files: withMi.length,
    avgMI: avg,
    medianMI: median(mis),
    low: mis.filter((m) => m < 10).length,
    moderate: mis.filter((m) => m >= 10 && m < 20).length,
    good: mis.filter((m) => m >= 20).length,
    histogram: bucketize(mis, [[0, 9.999, '0–9', 'bad'], [10, 19.999, '10–19', 'warn'], [20, 39.999, '20–39', 'ok'], [40, 59.999, '40–59', 'ok'], [60, 79.999, '60–79', 'good'], [80, 100, '80–100', 'good']]),
    lowest: [...withMi].filter((f) => f.code >= 10).sort((a, b) => a.mi - b.mi).slice(0, 25).map((f) => ({ path: f.path, lang: f.lang, code: f.code, cx: f.cx, mi: f.mi, hv: f.hv })),
    halstead: {
      volume: hal.volume,
      effort: hal.effort,
      difficulty: hal.diffW ? hal.diffSum / hal.diffW : 0,
      bugs: hal.volume / 3000, // Halstead의 예상 결함 수 B = V / 3000
      timeHours: hal.effort / 18 / 3600, // T = E / 18초
    },
    largestVolume: [...withMi].sort((a, b) => b.hv - a.hv).slice(0, 10).map((f) => ({ path: f.path, lang: f.lang, code: f.code, hv: f.hv, mi: f.mi })),
  };
}

// ───────────────────────── 코드 블록 중복 (복사-붙여넣기) ─────────────────────────
const DUP_K = 6; // 연속 6줄 이상 동일하면 중복 블록으로 판단
function detectDuplication(inputs, files) {
  const seen = new Map();
  const marks = inputs.map((x) => new Uint8Array(x.h.length));
  const pairs = new Map();
  const SHIFT = 16777216;
  inputs.forEach((x, fi) => {
    const h = x.h;
    for (let i = 0; i + DUP_K <= h.length; i++) {
      let a = 0x811c9dc5, b = 7, chars = 0;
      for (let k = 0; k < DUP_K; k++) {
        a = Math.imul(a ^ h[i + k], 16777619);
        b = (Math.imul(b, 31) + h[i + k]) | 0;
        chars += x.len[i + k];
      }
      if (chars < 80) continue; // 너무 짧은 블록은 무시
      const key = (a >>> 0) * 2097152 + ((b >>> 0) & 0x1fffff);
      const prev = seen.get(key);
      if (prev === undefined) { seen.set(key, fi * SHIFT + i); continue; }
      const pf = Math.floor(prev / SHIFT), pi = prev % SHIFT;
      if (pf === fi && Math.abs(pi - i) < DUP_K) continue;
      for (let k = 0; k < DUP_K; k++) { marks[fi][i + k] = 1; marks[pf][pi + k] = 1; }
      const pk = `${pf}:${fi}`;
      let p = pairs.get(pk);
      if (!p) pairs.set(pk, (p = { a: pf, b: fi, windows: 0, lineA: inputs[pf].line[pi], lineB: x.line[i], lastA: -10, lastB: -10, blocks: 0 }));
      p.windows++;
      if (pi !== p.lastA + 1 || i !== p.lastB + 1) p.blocks++; // 이어지지 않으면 새 블록
      p.lastA = pi; p.lastB = i;
    }
  });
  let dupLines = 0, sigTotal = 0;
  const perFile = [];
  inputs.forEach((x, fi) => {
    const c = marks[fi].reduce((a, v) => a + v, 0);
    sigTotal += x.h.length;
    dupLines += c;
    if (c) {
      files[x.idx].dup = c;
      perFile.push({ path: files[x.idx].path, lang: files[x.idx].lang, dup: c, sig: x.h.length, ratio: c / x.h.length });
    }
  });
  const pairList = [...pairs.values()].map((p) => ({
    a: files[inputs[p.a].idx].path, b: files[inputs[p.b].idx].path, lineA: p.lineA, lineB: p.lineB,
    lines: p.windows + (DUP_K - 1) * p.blocks, blocks: p.blocks, same: p.a === p.b,
  })).sort((x, y) => y.lines - x.lines);
  const srcIdx = inputs.map((x, fi) => fi).filter((fi) => files[inputs[fi].idx].cat === 'source');
  const srcSig = srcIdx.reduce((a, fi) => a + inputs[fi].h.length, 0);
  const srcDup = srcIdx.reduce((a, fi) => a + (files[inputs[fi].idx].dup || 0), 0);
  return {
    minLines: DUP_K,
    sourceRatio: srcSig ? srcDup / srcSig : 0,
    sourceDuplicatedLines: srcDup,
    analyzedLines: sigTotal,
    duplicatedLines: dupLines,
    ratio: sigTotal ? dupLines / sigTotal : 0,
    filesWithDup: perFile.length,
    pairCount: pairList.length,
    topFiles: perFile.sort((a, b) => b.dup - a.dup).slice(0, 25),
    topPairs: pairList.slice(0, 30),
  };
}

// ───────────────────────── 구조 통계 ─────────────────────────
function structureReport(files, root, summary) {
  const text = files.filter((f) => !f.bin && !f.gen && !f.min);
  const dirs = [];
  const walk = (d, depth) => {
    const direct = d.children.filter((c) => c.t === 'f').length;
    const sub = d.children.filter((c) => c.t === 'd').length;
    dirs.push({ path: d.path || '(루트)', files: direct, subdirs: sub, depth });
    for (const c of d.children) if (c.t === 'd') walk(c, depth + 1);
  };
  walk(root, 0);
  const deepest = [...files].sort((a, b) => b.path.split('/').length - a.path.split('/').length)[0];
  const extDirs = dirs.filter((d) => d.files > 0);
  return {
    fileLengths: bucketize(text.map((f) => f.lines), [[0, 50, '1–50'], [51, 100, '51–100'], [101, 200, '101–200'], [201, 500, '201–500'], [501, 1000, '501–1K'], [1001, 2000, '1K–2K'], [2001, Infinity, '2K+']]),
    depthDist: Array.from({ length: summary.maxDepth + 1 }, (_, i) => ({ label: String(i), count: files.filter((f) => f.path.split('/').length - 1 === i).length })),
    avgFilesPerDir: extDirs.length ? extDirs.reduce((a, d) => a + d.files, 0) / extDirs.length : 0,
    crowded: [...dirs].sort((a, b) => b.files - a.files).slice(0, 10),
    emptyishDirs: dirs.filter((d) => d.files === 0 && d.subdirs === 1).length, // 하위 폴더 하나만 감싸는 폴더
    deepestPath: deepest ? deepest.path : '',
    avgDepth: files.length ? files.reduce((a, f) => a + f.path.split('/').length - 1, 0) / files.length : 0,
  };
}

// 최상위 폴더(모듈)별 지표
function modulesReport(files) {
  const map = new Map();
  for (const f of files) {
    const i = f.path.indexOf('/');
    const key = i < 0 ? '(루트 파일)' : f.path.slice(0, i);
    let m = map.get(key);
    if (!m) map.set(key, (m = { name: key, files: 0, code: 0, comment: 0, bytes: 0, cx: 0, cxCode: 0, test: 0, src: 0, dup: 0, miSum: 0, miW: 0, fn: 0, langs: {} }));
    m.files++; m.code += f.code; m.comment += f.comment; m.bytes += f.size; m.dup += f.dup || 0; m.fn += f.fn;
    if (f.cx && !f.gen && !f.min) { m.cx += f.cx; m.cxCode += f.code; }
    if (f.cat === 'test') m.test += f.code;
    if (f.cat === 'source') m.src += f.code;
    if (f.mi != null) { m.miSum += f.mi * f.code; m.miW += f.code; }
    if (f.lang && f.code) m.langs[f.lang] = (m.langs[f.lang] || 0) + f.code;
  }
  return [...map.values()].map((m) => ({
    name: m.name, files: m.files, code: m.code, bytes: m.bytes, cx: m.cx, fn: m.fn,
    density: m.cxCode ? (m.cx / m.cxCode) * 100 : 0,
    commentRatio: m.code + m.comment ? m.comment / (m.code + m.comment) : 0,
    testRatio: m.src + m.test ? m.test / (m.src + m.test) : 0,
    mi: m.miW ? m.miSum / m.miW : null,
    dupRatio: m.code ? Math.min(1, m.dup / m.code) : 0,
    lang: (Object.entries(m.langs).filter(([l]) => ['programming', 'markup'].includes(LANGUAGES[l]?.type)).sort((a, b) => b[1] - a[1])[0] || Object.entries(m.langs).sort((a, b) => b[1] - a[1])[0])?.[0] || null,
  })).sort((a, b) => b.code - a.code);
}

const pick = (f) => ({ path: f.path, lang: f.lang, size: f.size, lines: f.lines, code: f.code, cx: f.cx, fn: f.fn, nest: f.nest });

function buildTree(files) {
  const root = { t: 'd', name: '', path: '', size: 0, code: 0, lines: 0, files: 0, cx: 0, children: [], _map: new Map(), _langs: {} };
  let dirCount = 0;
  for (const f of files) {
    const parts = f.path.split('/');
    let node = root;
    const chain = [root];
    for (let i = 0; i < parts.length - 1; i++) {
      let next = node._map.get(parts[i]);
      if (!next) {
        next = { t: 'd', name: parts[i], path: parts.slice(0, i + 1).join('/'), size: 0, code: 0, lines: 0, files: 0, cx: 0, children: [], _map: new Map(), _langs: {} };
        node._map.set(parts[i], next);
        node.children.push(next);
        dirCount++;
      }
      node = next;
      chain.push(node);
    }
    node.children.push({ t: 'f', name: parts[parts.length - 1], path: f.path, size: f.size, code: f.code, lines: f.lines, cx: f.cx, lang: f.lang, cat: f.cat });
    for (const d of chain) {
      d.size += f.size; d.code += f.code; d.lines += f.lines; d.files++; d.cx += f.cx;
      if (f.lang && f.code) d._langs[f.lang] = (d._langs[f.lang] || 0) + f.code;
    }
  }
  const finalize = (d) => {
    const top = Object.entries(d._langs).sort((a, b) => b[1] - a[1])[0];
    d.lang = top ? top[0] : null;
    delete d._map; delete d._langs;
    for (const c of d.children) if (c.t === 'd') finalize(c);
    d.children.sort((a, b) => (b.t === 'd') - (a.t === 'd') || b.size - a.size);
  };
  finalize(root);
  return { root, dirCount };
}

const clamp = (v) => Math.max(0, Math.min(100, v));

function computeScore(summary, cx, langCount, files) {
  const code = summary.code;
  // 규모는 100줄(0점) ~ 100만 줄(100점) 로그 스케일
  const parts = [
    { key: 'size', label: '코드 규모', value: `${code.toLocaleString()} 줄`, score: clamp(((Math.log10(code + 1) - 2) / 4) * 100), weight: 0.45 },
    { key: 'density', label: '분기 밀도', value: `${cx.density.toFixed(1)} / 100줄`, score: clamp((cx.density / 25) * 100), weight: 0.15 },
    { key: 'nesting', label: '중첩 깊이', value: `평균 ${cx.avgNesting.toFixed(1)}`, score: clamp((cx.avgNesting / 8) * 100), weight: 0.1 },
    { key: 'langs', label: '언어 다양성', value: `${langCount}개 언어`, score: clamp((langCount / 8) * 100), weight: 0.1 },
    { key: 'structure', label: '구조 규모', value: `${summary.files.toLocaleString()}개 파일 · 깊이 ${summary.maxDepth}`, score: clamp((Math.log10(summary.files + 1) / 4.5) * 70 + (summary.maxDepth / 12) * 30), weight: 0.2 },
  ];
  const overall = Math.round(parts.reduce((a, p) => a + p.score * p.weight, 0));
  const label = overall < 20 ? '매우 단순' : overall < 40 ? '단순' : overall < 60 ? '보통' : overall < 80 ? '복잡' : '매우 복잡';
  const grades = [[1_000, 'XS', '아주 작은 프로젝트'], [10_000, 'S', '작은 프로젝트'], [50_000, 'M', '중간 규모'], [250_000, 'L', '큰 프로젝트'], [1_000_000, 'XL', '대규모'], [Infinity, 'XXL', '초대형']];
  const g = grades.find(([lim]) => code < lim);
  return { overall, label, parts, sizeGrade: g[1], sizeLabel: g[2] };
}

// Basic COCOMO (organic) — 참고용 추정치
function cocomo(sloc) {
  const kloc = sloc / 1000;
  const effort = 2.4 * Math.pow(kloc, 1.05);
  const schedule = effort > 0 ? 2.5 * Math.pow(effort, 0.38) : 0;
  return { kloc, effortPM: effort, scheduleMonths: schedule, people: schedule ? effort / schedule : 0 };
}
